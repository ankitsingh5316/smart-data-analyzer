CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  preferences JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS signup_otps (
  id TEXT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  otp_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_signup_otps_email ON signup_otps (email, created_at);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reset_user ON password_reset_tokens (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reset_hash ON password_reset_tokens (token_hash);

CREATE TABLE IF NOT EXISTS datasets (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name VARCHAR(180) NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  stored_path VARCHAR(500) NOT NULL,
  file_type TEXT NOT NULL CHECK (file_type IN ('csv', 'xlsx', 'xls')),
  file_size BIGINT NOT NULL DEFAULT 0,
  row_count INTEGER NOT NULL DEFAULT 0,
  column_count INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'processing' CHECK (status IN ('processing', 'ready', 'failed')),
  duplicate_count INTEGER NOT NULL DEFAULT 0,
  missing_value_count INTEGER NOT NULL DEFAULT 0,
  error_message VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_datasets_user_created ON datasets (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_datasets_user_status ON datasets (user_id, status);

CREATE TABLE IF NOT EXISTS dataset_columns (
  id TEXT PRIMARY KEY,
  dataset_id TEXT NOT NULL REFERENCES datasets (id) ON DELETE CASCADE,
  column_name VARCHAR(180) NOT NULL,
  column_key VARCHAR(64) NOT NULL,
  data_type TEXT NOT NULL DEFAULT 'string' CHECK (data_type IN ('string', 'number', 'date', 'boolean')),
  ordinal INTEGER NOT NULL,
  null_count INTEGER NOT NULL DEFAULT 0,
  unique_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (dataset_id, column_key)
);

CREATE INDEX IF NOT EXISTS idx_columns_dataset_ordinal ON dataset_columns (dataset_id, ordinal);

CREATE TABLE IF NOT EXISTS dataset_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id TEXT NOT NULL REFERENCES datasets (id) ON DELETE CASCADE,
  row_index INTEGER NOT NULL,
  row_hash CHAR(64) NOT NULL,
  data JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_records_dataset_row ON dataset_records (dataset_id, row_index);
CREATE INDEX IF NOT EXISTS idx_records_dataset_hash ON dataset_records (dataset_id, row_hash);

CREATE TABLE IF NOT EXISTS saved_filters (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  dataset_id TEXT NOT NULL REFERENCES datasets (id) ON DELETE CASCADE,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(500),
  logic TEXT NOT NULL DEFAULT 'AND' CHECK (logic IN ('AND', 'OR')),
  conditions JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_filters_user_dataset ON saved_filters (user_id, dataset_id, updated_at);

CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  dataset_id TEXT REFERENCES datasets (id) ON DELETE SET NULL,
  saved_filter_id TEXT REFERENCES saved_filters (id) ON DELETE SET NULL,
  title VARCHAR(200) NOT NULL,
  format TEXT NOT NULL CHECK (format IN ('xlsx', 'csv', 'pdf')),
  selected_columns JSONB NOT NULL,
  filter_snapshot JSONB,
  status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'processing', 'completed', 'failed')),
  file_path VARCHAR(500),
  file_size BIGINT,
  record_count INTEGER,
  summary JSONB,
  error_message VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_reports_user_created ON reports (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reports_user_status ON reports (user_id, status);

CREATE TABLE IF NOT EXISTS report_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id TEXT NOT NULL REFERENCES reports (id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  action VARCHAR(32) NOT NULL,
  details VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_history_user_created ON report_history (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_history_report ON report_history (report_id, created_at);
